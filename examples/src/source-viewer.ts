export interface ExampleSourceFile {
  readonly code: string;
  readonly html: string;
  readonly styles: string;
  readonly filename: string;
  readonly language: string;
}
export interface ExampleSource {
  readonly variants: Readonly<
    Record<"ts" | "js", { readonly files: readonly ExampleSourceFile[]; readonly download: string }>
  >;
}

export function createSourceViewer(panel: HTMLDetailsElement) {
  const workspace = panel.querySelector<HTMLElement>(".source-workspace")!;
  const content = panel.querySelector<HTMLElement>(".source-code")!;
  const filename = panel.querySelector<HTMLElement>(".source-filename")!;
  const tabs = panel.querySelector<HTMLElement>(".source-tabs")!;
  const copy = panel.querySelector<HTMLButtonElement>(".copy-source")!;
  const wrap = panel.querySelector<HTMLButtonElement>(".wrap-source")!;
  const theme = panel.querySelector<HTMLButtonElement>(".theme-source")!;
  const expand = panel.querySelector<HTMLButtonElement>(".expand-source")!;
  const feedback = panel.querySelector<HTMLElement>(".copy-feedback")!;
  const meta = panel.querySelector<HTMLElement>(".source-meta")!;
  const languages = panel.querySelector<HTMLElement>(".source-languages")!;
  const download = panel.querySelector<HTMLAnchorElement>(".source-download")!;
  const dialog = document.createElement("dialog");
  dialog.className = "source-dialog";
  dialog.setAttribute("aria-label", "源码阅读");
  panel.append(dialog);
  const listeners = new AbortController();
  const signal = listeners.signal;
  let source: ExampleSource | undefined;
  let selected = 0;
  let language: "ts" | "js" = "ts";
  let version = 0;
  let reset: ReturnType<typeof setTimeout> | undefined;
  const resetCopy = (): void => {
    version++;
    clearTimeout(reset);
    feedback.textContent = "";
  };
  const close = (): void => {
    panel.insertBefore(workspace, dialog);
    expand.textContent = "展开阅读";
    expand.setAttribute("aria-expanded", "false");
  };
  dialog.addEventListener(
    "close",
    () => {
      if (!dialog.open) {
        close();
        if (panel.open) expand.focus();
      }
    },
    { signal },
  );
  const select = (index: number, focus = false): void => {
    const file = source?.variants[language].files[index];
    if (!file) return;
    resetCopy();
    selected = index;
    filename.textContent = file.filename;
    const label =
      (
        {
          ts: "TypeScript",
          js: "JavaScript",
          html: "HTML",
          json: "JSON",
          md: "Markdown",
        } as Record<string, string>
      )[file.language] ?? file.language;
    meta.textContent = `${file.code.trimEnd().split("\n").length} 行 · ${label} · 独立用法`;
    const style = document.createElement("style");
    style.textContent = file.styles;
    // Only escaped HTML generated by our build plugin is accepted here.
    content.innerHTML = file.html;
    content.prepend(style);
    content.querySelector<HTMLElement>(".expressive-code")!.dataset.codeTheme =
      workspace.dataset.codeTheme;
    const pre = content.querySelector("pre")!;
    pre.classList.toggle("wrap", workspace.dataset.wrap === "true");
    pre.tabIndex = 0;
    pre.setAttribute("role", "region");
    pre.setAttribute("aria-label", `${label} 源码：${file.filename}`);
    content.setAttribute("aria-labelledby", `source-tab-${index}`);
    for (const [i, tab] of Array.from(
      tabs.querySelectorAll<HTMLButtonElement>("button"),
    ).entries()) {
      tab.setAttribute("aria-selected", String(i === index));
      tab.tabIndex = i === index ? 0 : -1;
      if (focus && i === index) tab.focus();
    }
    copy.disabled = false;
    expand.disabled = false;
  };
  const clear = (): void => {
    if (dialog.open) dialog.close();
    close();
    resetCopy();
    source = undefined;
    selected = 0;
    copy.disabled = true;
    expand.disabled = true;
    filename.textContent = "正在加载源码…";
    meta.textContent = "";
    content.replaceChildren();
    tabs.replaceChildren();
    download.removeAttribute("href");
    panel.open = false;
  };
  tabs.addEventListener(
    "click",
    (event) => {
      const button = (event.target as Element).closest<HTMLButtonElement>("[data-source-index]");
      if (button) select(Number(button.dataset.sourceIndex));
    },
    { signal },
  );
  tabs.addEventListener(
    "keydown",
    (event) => {
      const index = Number((event.target as HTMLElement).dataset.sourceIndex);
      const length = source?.variants[language].files.length ?? 0;
      if (!length || !Number.isInteger(index)) return;
      const next =
        event.key === "ArrowRight"
          ? (index + 1) % length
          : event.key === "ArrowLeft"
            ? (index + length - 1) % length
            : event.key === "Home"
              ? 0
              : event.key === "End"
                ? length - 1
                : undefined;
      if (next !== undefined) {
        event.preventDefault();
        select(next, true);
      }
    },
    { signal },
  );
  wrap.addEventListener(
    "click",
    () => {
      const enabled = workspace.dataset.wrap !== "true";
      workspace.dataset.wrap = String(enabled);
      content.querySelector("pre")?.classList.toggle("wrap", enabled);
      wrap.setAttribute("aria-pressed", String(enabled));
    },
    { signal },
  );
  theme.addEventListener(
    "click",
    () => {
      const light = workspace.dataset.codeTheme !== "light";
      workspace.dataset.codeTheme = light ? "light" : "dark";
      const block = content.querySelector<HTMLElement>(".expressive-code");
      if (block) block.dataset.codeTheme = workspace.dataset.codeTheme;
      theme.textContent = light ? "深色主题" : "浅色主题";
    },
    { signal },
  );
  expand.addEventListener(
    "click",
    () => {
      if (dialog.open) dialog.close();
      else {
        dialog.append(workspace);
        dialog.showModal();
        expand.textContent = "收起阅读";
        expand.setAttribute("aria-expanded", "true");
        expand.focus();
      }
    },
    { signal },
  );
  copy.addEventListener(
    "click",
    async () => {
      const file = source?.variants[language].files[selected];
      if (!file) return;
      const request = ++version;
      copy.disabled = true;
      feedback.textContent = "正在复制…";
      try {
        await navigator.clipboard.writeText(file.code);
        if (request === version) feedback.textContent = "已复制";
      } catch {
        if (request === version) feedback.textContent = "无法复制，请选中代码后手动复制。";
      } finally {
        if (request === version) {
          copy.disabled = !source;
          clearTimeout(reset);
          reset = setTimeout(() => {
            feedback.textContent = "";
          }, 2200);
        }
      }
    },
    { signal },
  );
  clear();
  const showFiles = (): void => {
    tabs.replaceChildren();
    for (const [index, file] of (source?.variants[language].files ?? []).entries()) {
      const tab = document.createElement("button");
      tab.type = "button";
      tab.id = `source-tab-${index}`;
      tab.dataset.sourceIndex = String(index);
      tab.setAttribute("role", "tab");
      tab.setAttribute("aria-controls", "source-content");
      tab.textContent = file.filename;
      tabs.append(tab);
    }
    for (const button of languages.querySelectorAll<HTMLButtonElement>("[data-source-language]"))
      button.setAttribute("aria-pressed", String(button.dataset.sourceLanguage === language));
    if (source) download.href = import.meta.env.BASE_URL + source.variants[language].download;
    download.download = "";
    select(0);
  };
  languages.addEventListener(
    "click",
    (event) => {
      const value = (event.target as Element).closest<HTMLElement>("[data-source-language]")
        ?.dataset.sourceLanguage;
      if (value !== "ts" && value !== "js") return;
      language = value;
      showFiles();
    },
    { signal },
  );
  return {
    clear,
    fail(): void {
      const wasOpen = panel.open;
      clear();
      filename.textContent = "示例代码加载失败";
      feedback.textContent = "示例代码暂时不可用，请刷新页面重试。";
      panel.open = wasOpen;
    },
    set(value: ExampleSource): void {
      const wasOpen = panel.open;
      clear();
      source = value;
      showFiles();
      panel.open = wasOpen;
    },
    destroy(): void {
      clear();
      listeners.abort();
      dialog.remove();
    },
  };
}
